// Generates the precache list and the cache version of sw.js from the files on disk.
//   node scripts/generate-sw.mjs           rewrites the GENERATED block of sw.js
//   node scripts/generate-sw.mjs --check   exits 1 (with a readable report) when sw.js is stale or the app references a missing file
// `npm run build:sw` runs the first form; `npm run check` runs the second one, so CI fails on a stale list.
//
// VERSION = first 12 hex chars of a sha256 over every precached file (path + content, text normalised to LF so a CRLF
// checkout on Windows and an LF checkout on Linux produce the same value). sw.js itself is not part of the hash.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, posix, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const RAIZ_POR_DEFECTO = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// What the service worker precaches: top-level files and folders (relative to the repo root).
export const ARCHIVOS_RAIZ = ['index.html', 'manifest.webmanifest'];
export const CARPETAS = ['css', 'js', 'icons', 'vendor'];
// Never shipped to the browser's cache on purpose (test tooling, loaded only on localhost with the test flag).
export const EXCLUIDOS = ['js/infrastructure/fakeGoogle.js'];
// A failed download of these must not abort the SW install (large third-party bundles that are lazy-loaded).
export const OPCIONALES_PREFIJOS = ['vendor/'];
const TEXTO = /\.(html|js|mjs|css|json|webmanifest|svg|txt|map)$/i;
const IGNORAR = new Set(['node_modules', '.git', '.DS_Store', 'Thumbs.db']);

export const MARCA_INICIO = '// >>> GENERATED by scripts/generate-sw.mjs (npm run build:sw). Do not edit by hand.';
export const MARCA_FIN = '// <<< GENERATED';

const aPosix = (p) => p.split(sep).join('/');

function recorrer(dir, base, salida) {
  if (!existsSync(dir)) return;
  for (const nombre of readdirSync(dir).sort()) {
    if (IGNORAR.has(nombre)) continue;
    const abs = join(dir, nombre);
    if (statSync(abs).isDirectory()) recorrer(abs, base, salida);
    else salida.push(aPosix(relative(base, abs)));
  }
}

// Sorted list of files (posix paths relative to the root) that the service worker precaches.
export function listarArchivos(raiz = RAIZ_POR_DEFECTO) {
  const out = [];
  for (const f of ARCHIVOS_RAIZ) if (existsSync(join(raiz, f))) out.push(f);
  for (const c of CARPETAS) recorrer(join(raiz, c), raiz, out);
  return out.filter((f) => !EXCLUIDOS.includes(f)).sort();
}

// Content hash of the precached files -> short version string.
export function calcularVersion(archivos, raiz = RAIZ_POR_DEFECTO) {
  const hash = createHash('sha256');
  for (const f of archivos) {
    let datos = readFileSync(join(raiz, f));
    if (TEXTO.test(f)) datos = Buffer.from(datos.toString('utf8').replace(/\r\n/g, '\n'), 'utf8');
    hash.update(f + '\0');
    hash.update(datos);
    hash.update('\0');
  }
  return hash.digest('hex').slice(0, 12);
}

export const esOpcional = (f) => OPCIONALES_PREFIJOS.some((p) => f.startsWith(p));

// The text that goes between the markers (LF line endings).
export function bloqueGenerado(archivos, version) {
  const urls = archivos.map((f) => `  './${f}',`).join('\n');
  const opc = archivos.filter(esOpcional).map((f) => `  './${f}',`).join('\n');
  return [
    MARCA_INICIO,
    `const VERSION = '${version}';`,
    'const SHELL = [',
    "  './',",
    urls,
    '];',
    '// Files whose download may fail without aborting the install (everything else is required).',
    'const OPCIONALES = [',
    opc,
    '];',
    MARCA_FIN,
  ].join('\n');
}

// Replaces the generated block of an existing sw.js text, keeping its line endings.
export function aplicarBloque(textoSw, bloque) {
  const i = textoSw.indexOf(MARCA_INICIO);
  const j = textoSw.indexOf(MARCA_FIN);
  if (i < 0 || j < i) throw new Error(`sw.js must contain the markers "${MARCA_INICIO}" and "${MARCA_FIN}"`);
  const crlf = textoSw.includes('\r\n');
  const nuevo = crlf ? bloque.replace(/\n/g, '\r\n') : bloque;
  return textoSw.slice(0, i) + nuevo + textoSw.slice(j + MARCA_FIN.length);
}

// ---- Consistency checks (visible errors instead of silent catches) ----
const sinComentarios = (src) => src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:'"`\\])\/\/.*$/gm, '$1');

// Relative imports/URLs that do not exist or that the service worker would not precache.
export function verificar(raiz = RAIZ_POR_DEFECTO, archivos = listarArchivos(raiz)) {
  const errores = [];
  const lista = new Set(archivos);
  const existe = (rel) => existsSync(join(raiz, rel));
  const comprobar = (desde, destino, tipo) => {
    if (EXCLUIDOS.includes(destino)) return;
    if (!existe(destino)) errores.push(`${desde}: ${tipo} "${destino}" does not exist`);
    else if (!lista.has(destino)) errores.push(`${desde}: ${tipo} "${destino}" exists but is not precached`);
  };

  for (const f of archivos.filter((x) => x.startsWith('js/') && x.endsWith('.js'))) {
    const src = sinComentarios(readFileSync(join(raiz, f), 'utf8'));
    const re = /(?:\bfrom\s*|\bimport\s*\(?\s*)(['"])(\.{1,2}\/[^'"`$]+)\1/g;
    for (let m; (m = re.exec(src));) comprobar(f, posix.normalize(posix.join(posix.dirname(f), m[2])), 'import');
    const us = /\buseStyles\(\s*(['"])([\w-]+)\1/g;
    for (let m; (m = us.exec(src));) comprobar(f, `css/views/${m[2]}.css`, 'useStyles stylesheet');
  }
  if (existe('index.html')) {
    const html = readFileSync(join(raiz, 'index.html'), 'utf8');
    const re = /\b(?:href|src)="(\.\/[^"#?]+)"/g;
    for (let m; (m = re.exec(html));) comprobar('index.html', posix.normalize(m[1]), 'reference');
  }
  for (const f of archivos.filter((x) => x.endsWith('.css'))) {
    const css = readFileSync(join(raiz, f), 'utf8');
    const re = /url\(\s*['"]?(\.{1,2}\/[^'")]+)['"]?\s*\)/g;
    for (let m; (m = re.exec(css));) comprobar(f, posix.normalize(posix.join(posix.dirname(f), m[1])), 'url()');
  }
  return [...new Set(errores)];
}

// Compares sw.js with what the disk says it should be. -> { ok, problemas[], version, esperado }
export function comprobar(raiz = RAIZ_POR_DEFECTO) {
  const archivos = listarArchivos(raiz);
  const version = calcularVersion(archivos, raiz);
  const esperado = aplicarBloque(readFileSync(join(raiz, 'sw.js'), 'utf8'), bloqueGenerado(archivos, version));
  const problemas = verificar(raiz, archivos);
  const actual = readFileSync(join(raiz, 'sw.js'), 'utf8');
  if (actual !== esperado) {
    const enSw = new Set([...actual.matchAll(/'\.\/([^']+)'/g)].map((m) => m[1]));
    const faltan = archivos.filter((f) => !enSw.has(f));
    const sobran = [...enSw].filter((f) => f && !archivos.includes(f));
    problemas.push(`sw.js is stale (expected VERSION ${version}). Run: npm run build:sw`
      + (faltan.length ? `\n    missing from SHELL: ${faltan.slice(0, 8).join(', ')}${faltan.length > 8 ? ` (+${faltan.length - 8})` : ''}` : '')
      + (sobran.length ? `\n    listed but not on disk: ${sobran.slice(0, 8).join(', ')}` : ''));
  }
  return { ok: !problemas.length, problemas, version, esperado, archivos };
}

export function generar(raiz = RAIZ_POR_DEFECTO) {
  const archivos = listarArchivos(raiz);
  const version = calcularVersion(archivos, raiz);
  const ruta = join(raiz, 'sw.js');
  const nuevo = aplicarBloque(readFileSync(ruta, 'utf8'), bloqueGenerado(archivos, version));
  writeFileSync(ruta, nuevo);
  return { version, total: archivos.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--check')) {
    const r = comprobar();
    if (!r.ok) {
      console.error('Service worker check FAILED:\n  - ' + r.problemas.join('\n  - '));
      process.exit(1);
    }
    console.log(`Service worker OK (${r.archivos.length} files, VERSION ${r.version})`);
  } else {
    const { version, total } = generar();
    console.log(`sw.js updated: ${total} files, VERSION ${version}`);
  }
}

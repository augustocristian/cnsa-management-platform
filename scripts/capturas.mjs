// Waits until the view is no longer loading, the sync has finished and the fonts have loaded.
async function estable(p, { espera = 250 } = {}) {
  await p
    .locator('#view .loading, .spinner, [aria-busy="true"]')
    .first()
    .waitFor({ state: 'detached', timeout: 8000 })
    .catch(() => {});
  await p.evaluate(() => document.fonts && document.fonts.ready).catch(() => {});
  await p
    .locator('.status-chip.st-sincronizado')
    .waitFor({ timeout: 4000 })
    .catch(() => {}); // "Pending" -> "Synced" (only in the account menu, so it is usually absent)
  await p.waitForLoadState('networkidle', { timeout: 4000 }).catch(() => {});
  await pausa(espera);
}


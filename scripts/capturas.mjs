//
//   npm run capturas                              all (desktop 1366x850 and mobile 390x844)
//   npm run capturas -- --solo=inicio,asistencia  only some (by id; see ESCENARIOS)
//   npm run capturas -- --dispositivo=movil       only desktop or only mobile
//   npm run capturas -- --concurrencia=2          simultaneous pages (default 4)
//   npm run capturas -- --salida=ruta/otra        output folder (default docs/screenshots)
//
// How it works: starts scripts/serve.mjs on a free port and opens the app with Playwright/Chromium. Two kinds of scenario:
//   - "simulated" (default): the simulated Google of the tests (js/infrastructure/fakeGoogle.js, localStorage 'cnl:test')
//     and the demo data (store.seedDemo), like the E2E tests: every view of a Drive-connected club.
//   - "real" (modo: 'real'): the real start flow WITHOUT the test adapter: the "Configuration needed" screen (no Client
//     ID), the "Connect Google Drive" screen (a Client ID in localStorage) and the product demo mode, entered through the
//     real "Try the demo" button.
// To make them reproducible: fixed clock (Wednesday 14-Oct-2026, 10:30 Madrid), Europe/Madrid time zone, English unless
// the scenario says another language, reduced motion, no service worker, animations and cursor disabled during the
// capture. Each scenario runs in its own clean context and they run in parallel with a limit. A capture is rejected (and
// not written) if there are console errors, 4xx/5xx responses, the view is left on loading or the PNG is suspiciously
// small; the process exits with code 1 if any fails. Images over MAX_KB are re-encoded as a 256-colour PNG
// (scripts/lib/paletaPng.mjs, pure JS). The training PDF is generated by the app itself and its first page is painted
// with pdfjs-dist.

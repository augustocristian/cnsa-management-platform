// Scrolls the element to the top of its scrollable container (window, dialog...) leaving "margen" px above it
async function desplazar(p, selector, margen = 0) {
  const el = p.locator(selector).first();
  await el.waitFor({ timeout: 8000 });
  await el.evaluate((e, m) => {
    let c = e.parentElement;
    while (c && !(c.scrollHeight > c.clientHeight + 4 && /(auto|scroll)/.test(getComputedStyle(c).overflowY)))
      c = c.parentElement;
    if (!c) {
      window.scrollTo(0, Math.max(0, e.getBoundingClientRect().top + window.scrollY - m));
      return;
    }
    c.scrollTop += e.getBoundingClientRect().top - c.getBoundingClientRect().top - m;
  }, margen);
  await pausa(200);
}

// Chooses the option whose text starts with "texto" in a <select> (also when several options share the label)
async function elegir(sel, texto) {
  await sel.evaluate((s, t) => {
    const o = [...s.options].reverse().find((x) => x.text.trim().startsWith(t));
    if (!o) throw new Error(`option "${t}" not found`);
    s.value = o.value;
    s.dispatchEvent(new Event('change', { bubbles: true }));
  }, texto);
  await pausa(150);
}


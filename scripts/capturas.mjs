// ---------- Running a scenario ----------
async function ejecutar(navegador, baseURL, esc, disp) {
  const nombre = `${disp}-${esc.id}`;
  const real = esc.modo === 'real';
  const ctx = await navegador.newContext({
    ...VISORES[disp],
    baseURL,
    locale: esc.locale || 'en-GB',
    timezoneId: ZONA,
    reducedMotion: 'reduce',
    colorScheme: esc.tema === 'dark' ? 'dark' : 'light',
    serviceWorkers: 'block',
    acceptDownloads: true,
  });
  const errores = [];
  try {
    await ctx.addInitScript(
      ([esReal, o, lang, tema, extra]) => {
        try {
          if (!esReal) {
            localStorage.setItem('cnl:test', '1');
            localStorage.setItem('cnl:test:opts', JSON.stringify(o));
          }
          localStorage.setItem('cnl:lang', lang);
          if (tema) localStorage.setItem('cnl:tema', tema);
          for (const [k, v] of Object.entries(extra)) localStorage.setItem(k, v);
        } catch (e) {
          /* ignore */
        }
      },
      [real, esc.opciones || DEMO, esc.idioma || 'en', esc.tema || '', esc.ls || {}],
    );
    const p = await ctx.newPage();
    p.setDefaultTimeout(10000);
    await p.clock.setFixedTime(AHORA);
    p.on('console', (m) => {
      if (m.type() === 'error') errores.push(`console: ${m.text()}`);
    });
    p.on('pageerror', (e) => errores.push(`pageerror: ${e.message}`));
    p.on('response', (r) => {
      if (r.url().startsWith(baseURL) && r.status() >= 400) errores.push(`HTTP ${r.status()} ${r.url()}`);
    });

    if (esc.sinShell) {
      await p.goto(`/#/${esc.ruta || ''}`);
      await estable(p, { espera: 400 });
    } else await entrar(p, esc.ruta);
    if (esc.paso) await esc.paso(p, { navegador, disp });
    await estable(p);

    await p.mouse.move(1, 1); // no "hover" elements from the pointer of the last action
    let png = esc.captura ? await esc.captura(p, { navegador, disp }) : null;
    if (!png) {
      const cuerpo = (await p.locator('body').innerText()).trim();
      if (cuerpo.length < 20) throw new Error('the screen is empty');
      if (await p.locator('#view .loading').count()) throw new Error('the view is still loading');
      png = await p.screenshot({ type: 'png', animations: 'disabled', caret: 'hide', fullPage: !!esc.paginaCompleta });
    }
    if (errores.length) throw new Error('errors on the page:\n  ' + [...new Set(errores)].join('\n  '));
    if (png.length < 6000) throw new Error(`suspiciously small capture (${png.length} bytes)`);
    let reducida = false;
    if (png.length > MAX_KB * 1024) {
      png = reducirPng(png);
      reducida = true;
    }
    writeFileSync(join(SALIDA, `${nombre}.png`), png);
    return { nombre, kb: Math.round(png.length / 1024), ok: true, reducida };
  } catch (e) {
    return { nombre, ok: false, error: e.message.split('\n').slice(0, 6).join('\n') };
  } finally {
    await ctx.close().catch(() => {});
  }
}

// ---------- Server and main loop ----------
const puertoLibre = () =>
  new Promise((ok, ko) => {
    const s = createServer();
    s.once('error', ko);
    s.listen(0, '127.0.0.1', () => {
      const { port } = s.address();
      s.close(() => ok(port));
    });
  });

async function main() {
  mkdirSync(SALIDA, { recursive: true });
  const puerto = await puertoLibre();
  const baseURL = `http://localhost:${puerto}`;
  const servidor = spawn(process.execPath, ['scripts/serve.mjs', String(puerto)], {
    cwd: RAIZ,
    stdio: ['ignore', 'pipe', 'inherit'],
  });
  await new Promise((ok, ko) => {
    const t = setTimeout(() => ko(new Error('The static server did not start')), 10_000);
    servidor.stdout.on('data', (d) => {
      if (String(d).includes('http://')) {
        clearTimeout(t);
        ok();
      }
    });
    servidor.once('exit', (c) => ko(new Error('The server exited with code ' + c)));
  });
  const navegador = await chromium.launch();
  let fallos;
  try {
    const tareas = [];
    for (const esc of ESCENARIOS) {
      if (SOLO && !SOLO.includes(esc.id)) continue;
      for (const disp of esc.dispositivos || ['escritorio', 'movil']) {
        if (DISP && DISP !== disp) continue;
        tareas.push([esc, disp]);
      }
    }
    if (!tareas.length) throw new Error('No scenario matches the filters');
    console.log(`Capturing ${tareas.length} screens (concurrency ${CONCURRENCIA}) into ${SALIDA}`);
    const cola = [...tareas];
    const resultados = [];
    const trabajador = async () => {
      for (let t = cola.shift(); t; t = cola.shift()) {
        let r = await ejecutar(navegador, baseURL, t[0], t[1]);
        if (!r.ok) r = await ejecutar(navegador, baseURL, t[0], t[1]); // one retry in case it was a flicker
        resultados.push(r);
        console.log(
          r.ok
            ? `  ok   ${r.nombre}.png (${r.kb} KB${r.reducida ? ', palette' : ''}${r.kb > MAX_KB ? ' - over ' + MAX_KB + ' KB' : ''})`
            : `  FAIL ${r.nombre}: ${r.error}`,
        );
      }
    };
    await Promise.all(Array.from({ length: Math.min(CONCURRENCIA, tareas.length) }, trabajador));
    fallos = resultados.filter((r) => !r.ok).length;
    console.log(`\n${resultados.length - fallos} screenshots generated, ${fallos} failed.`);
  } finally {
    await navegador.close();
    servidor.removeAllListeners('exit');
    servidor.kill();
  }
  process.exit(fallos ? 1 : 0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
